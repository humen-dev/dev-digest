import { Document, Scalar } from 'yaml';
import type { CiPostAs, CiTrigger } from '@devdigest/shared';
import {
  ARTIFACT_NAME,
  BASE_DIR,
  BOOTSTRAP_NOTICE,
  JOB_ID,
  OPENROUTER_SECRET_NAME,
  PINNED_ACTIONS,
  RESULT_FILENAME,
  RUNNER_ENTRY,
  RUN_META_FILENAME,
  WORKFLOW_NAME,
} from '../constants.js';

/**
 * SPEC-08 §3.5 — the generated GitHub Actions workflow. Pure.
 *
 * Invariant: no `${{ … }}` expression is ever placed inside a `run:` value
 * (AC-26). The only `run:` bodies are fixed constants; every variable value
 * (PR title, repo, SHA) reaches them through the step's `env:` block. The
 * document is built as an object tree and serialised by `yaml`, never by
 * string concatenation, so hostile values cannot break out of the structure.
 */

export interface BuildWorkflowInput {
  triggers: readonly CiTrigger[];
  postAs: CiPostAs;
}

/** Canonical trigger order (AC-17). */
const CANONICAL_TRIGGERS: readonly CiTrigger[] = ['opened', 'synchronize', 'reopened'];
const POST_AS_VALUES: readonly CiPostAs[] = ['github_review', 'pr_comment', 'none'];

const HEADER_COMMENT =
  ' Generated by DevDigest (export to CI).\n' +
  ' Re-running "Update CI config" in DevDigest regenerates this file from the\n' +
  " agent's current configuration.";

const GUARD_ID = 'guard';
const GUARD_PASSED = `steps.${GUARD_ID}.outputs.installed == 'true'`;
const RUNNER_BASE_PATH = `${BASE_DIR}/${RUNNER_ENTRY}`;

/** Fixed script: only the base-branch checkout runs before this (EC-25). */
const GUARD_SCRIPT =
  `if [ -f ${RUNNER_BASE_PATH} ]; then\n` +
  `  echo "installed=true" >> "$GITHUB_OUTPUT"\n` +
  `else\n` +
  `  echo "installed=false" >> "$GITHUB_OUTPUT"\n` +
  `  echo "::notice::${BOOTSTRAP_NOTICE}"\n` +
  `fi\n`;

/** Fixed script: every value is read from env at runtime (AC-26, AC-50). */
const RUN_META_SCRIPT =
  `node -e "const fs=require('fs');const e=process.env;fs.writeFileSync('${RUN_META_FILENAME}',JSON.stringify({` +
  `commit_sha:e.DEVDIGEST_COMMIT_SHA,repository:e.DEVDIGEST_REPOSITORY,` +
  `repository_id:Number(e.DEVDIGEST_REPOSITORY_ID),pr_number:Number(e.DEVDIGEST_PR_NUMBER),` +
  `pr_title:e.DEVDIGEST_PR_TITLE}));"`;

function normalizeTriggers(triggers: readonly CiTrigger[]): CiTrigger[] {
  const requested = new Set<string>(triggers);
  const kept = CANONICAL_TRIGGERS.filter((t) => requested.has(t));
  return kept.length > 0 ? kept : [CANONICAL_TRIGGERS[0]!];
}

function permissionsBlock(postAs: CiPostAs): Record<string, string> {
  return postAs === 'none' ? { contents: 'read' } : { contents: 'read', 'pull-requests': 'write' };
}

function pin(action: { repo: string; sha: string }): string {
  return `${action.repo}@${action.sha}`;
}

export function buildWorkflowYaml(input: BuildWorkflowInput): string {
  if (!POST_AS_VALUES.includes(input.postAs)) {
    throw new Error(`Invalid post_as value for workflow generation: ${String(input.postAs)}`);
  }
  const postAs = input.postAs;
  const triggers = normalizeTriggers(input.triggers);
  const afterGuard = GUARD_PASSED;
  const alwaysAfterGuard = `always() && ${GUARD_PASSED}`;

  const workflow = {
    name: WORKFLOW_NAME,
    // `pull_request`, never `pull_request_target` — no secrets for fork code.
    on: { pull_request: { types: triggers } },
    concurrency: {
      group: 'devdigest-review-${{ github.event.pull_request.number }}',
      'cancel-in-progress': true,
    },
    jobs: {
      [JOB_ID]: {
        'runs-on': 'ubuntu-latest',
        'timeout-minutes': 15,
        // Second, independent defence: never run for a PR opened from another
        // repository (a fork). Compare the head repo with this repo instead of
        // reading `head.repo.fork`: that flag is also true for every same-repo PR
        // when the installed repository is itself a fork, which would skip all runs.
        if: 'github.event.pull_request.head.repo.full_name == github.repository',
        permissions: permissionsBlock(postAs),
        steps: [
          {
            name: 'Checkout base branch',
            uses: pin(PINNED_ACTIONS.checkout),
            with: {
              ref: '${{ github.event.pull_request.base.sha }}',
              path: BASE_DIR,
              'persist-credentials': false,
              'sparse-checkout': '.devdigest',
            },
          },
          { name: 'Check DevDigest is installed', id: GUARD_ID, run: GUARD_SCRIPT },
          {
            name: 'Setup Node',
            if: afterGuard,
            uses: pin(PINNED_ACTIONS.setupNode),
            with: { 'node-version': '22' },
          },
          {
            name: 'Run DevDigest review',
            id: 'review',
            if: afterGuard,
            env: {
              OPENROUTER_API_KEY: `\${{ secrets.${OPENROUTER_SECRET_NAME} }}`,
              GITHUB_TOKEN: '${{ secrets.GITHUB_TOKEN }}',
              GITHUB_REPOSITORY: '${{ github.repository }}',
              PR_NUMBER: '${{ github.event.pull_request.number }}',
              DEVDIGEST_DIR: `${BASE_DIR}/.devdigest`,
              DEVDIGEST_POST_AS: postAs,
              DEVDIGEST_RESULT_PATH: RESULT_FILENAME,
            },
            run: `node ${RUNNER_BASE_PATH}`,
          },
          {
            name: 'Write run metadata',
            if: alwaysAfterGuard,
            env: {
              DEVDIGEST_COMMIT_SHA: '${{ github.event.pull_request.head.sha }}',
              DEVDIGEST_REPOSITORY: '${{ github.repository }}',
              DEVDIGEST_REPOSITORY_ID: '${{ github.event.repository.id }}',
              DEVDIGEST_PR_NUMBER: '${{ github.event.pull_request.number }}',
              DEVDIGEST_PR_TITLE: '${{ github.event.pull_request.title }}',
            },
            run: RUN_META_SCRIPT,
          },
          {
            name: 'Upload result artifact',
            if: alwaysAfterGuard,
            uses: pin(PINNED_ACTIONS.uploadArtifact),
            with: {
              name: ARTIFACT_NAME,
              path: `${RESULT_FILENAME}\n${RUN_META_FILENAME}\n`,
              'if-no-files-found': 'warn',
            },
          },
        ],
      },
    },
  };

  const doc = new Document(workflow);
  doc.commentBefore = HEADER_COMMENT;

  const stepsPath = ['jobs', JOB_ID, 'steps'];
  annotateUses(doc, [...stepsPath, 0, 'uses'], PINNED_ACTIONS.checkout.version);
  annotateUses(doc, [...stepsPath, 2, 'uses'], PINNED_ACTIONS.setupNode.version);
  annotateUses(doc, [...stepsPath, 5, 'uses'], PINNED_ACTIONS.uploadArtifact.version);

  // lineWidth 0: never fold scalars, so every `run:` stays on its own lines.
  return doc.toString({ lineWidth: 0 });
}

function annotateUses(doc: Document, path: (string | number)[], version: string): void {
  const node = doc.getIn(path, true);
  if (node instanceof Scalar) node.comment = ` ${version}`;
}
